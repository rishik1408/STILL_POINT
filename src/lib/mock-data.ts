// Deterministic point-in-polygon helper for offline / demo mode
export function findWardByCoordinates(lat: number, lng: number): Authority | null {
  for (const authority of MOCK_AUTHORITIES) {
    const poly = authority.ward_polygon as { coordinates: number[][][] };
    if (!poly || !poly.coordinates || !poly.coordinates[0]) continue;
    
    // Ray-casting algorithm
    const ring = poly.coordinates[0];
    let inside = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const xi = ring[i][0], yi = ring[i][1];
      const xj = ring[j][0], yj = ring[j][1];
      
      const intersect = ((yi > lat) !== (yj > lat)) &&
        (lng < (xj - xi) * (lat - yi) / (yj - yi) + xi);
      if (intersect) inside = !inside;
    }
    
    if (inside) return authority;
  }
  
  // Default to nearest or Ward A if within Mumbai bounds
  return MOCK_AUTHORITIES[0];
}
